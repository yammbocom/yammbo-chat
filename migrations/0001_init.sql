-- Chat persistence: conversations, messages, leads, feedback.
-- Timestamps are epoch milliseconds. Retention (see scheduled() in src/index.ts):
-- conversations/messages/feedback 90 days, leads 365 days.

CREATE TABLE conversations (
  id TEXT PRIMARY KEY,            -- sessionId generated by the widget
  created_at INTEGER NOT NULL,
  updated_at INTEGER NOT NULL,
  page_url TEXT,
  product TEXT,
  lang TEXT,
  ip_hash TEXT,                   -- sha256(ip|UTC date|salt): rotates daily, never the raw IP
  msg_count INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE messages (
  id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL,
  role TEXT NOT NULL,             -- 'user' | 'assistant'
  content TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  provider TEXT,                  -- 'groq' | 'gemini' (assistant rows)
  rag_hits INTEGER,               -- KB chunks used (0 = fallback index)
  handoff INTEGER NOT NULL DEFAULT 0,
  latency_ms INTEGER
);
CREATE INDEX idx_messages_session ON messages (session_id);
CREATE INDEX idx_messages_created ON messages (created_at);

CREATE TABLE leads (
  id TEXT PRIMARY KEY,
  created_at INTEGER NOT NULL,
  session_id TEXT,
  name TEXT,
  email TEXT,
  phone TEXT,
  channel TEXT,
  message TEXT,
  lang TEXT,
  page_url TEXT,
  notify TEXT                     -- JSON: per-channel notification result
);
CREATE INDEX idx_leads_created ON leads (created_at);

CREATE TABLE feedback (
  message_id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL,
  rating INTEGER NOT NULL CHECK (rating IN (1, -1)),
  created_at INTEGER NOT NULL
);
